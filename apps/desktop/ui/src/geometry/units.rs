/// The arithmetic derive_more gives GPUI's unit newtypes: `+ - += -=` with the same type, and
/// `/ /=` by the inner scalar.
macro_rules! unit_ops {
    ($t:ident, $inner:ty) => {
        impl Add for $t {
            type Output = Self;
            fn add(self, rhs: Self) -> Self {
                $t(self.0 + rhs.0)
            }
        }
        impl AddAssign for $t {
            fn add_assign(&mut self, rhs: Self) {
                self.0 += rhs.0;
            }
        }
        impl Sub for $t {
            type Output = Self;
            fn sub(self, rhs: Self) -> Self {
                $t(self.0 - rhs.0)
            }
        }
        impl SubAssign for $t {
            fn sub_assign(&mut self, rhs: Self) {
                self.0 -= rhs.0;
            }
        }
        impl Div<$inner> for $t {
            type Output = Self;
            fn div(self, rhs: $inner) -> Self {
                $t(self.0 / rhs)
            }
        }
    };
}

macro_rules! neg_and_div_assign {
    ($t:ident, $inner:ty) => {
        impl Neg for $t {
            type Output = Self;
            fn neg(self) -> Self {
                $t(-self.0)
            }
        }
        impl DivAssign<$inner> for $t {
            fn div_assign(&mut self, rhs: $inner) {
                self.0 /= rhs;
            }
        }
    };
}

unit_ops!(Radians, f32);
unit_ops!(Percentage, f32);
unit_ops!(Pixels, f32);
unit_ops!(DevicePixels, i32);
unit_ops!(ScaledPixels, f32);
neg_and_div_assign!(Radians, f32);
neg_and_div_assign!(Percentage, f32);
neg_and_div_assign!(Pixels, f32);
neg_and_div_assign!(ScaledPixels, f32);
