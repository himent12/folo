/// What to print instead of opening the app (`--help`, `--version`), if `args` (without the program name) ask
/// for it.
fn info_text<S: AsRef<str>>(args: &[S]) -> Option<String> {
    let has = |flags: &[&str]| args.iter().any(|a| flags.contains(&a.as_ref()));
    if has(&["-h", "--help"]) {
        Some(USAGE.to_string())
    } else if has(&["-V", "--version"]) {
        Some(format!(
            "folo-desktop {}
",
            env!("CARGO_PKG_VERSION")
        ))
    } else {
        None
    }
}

/// The options that take a value, and those that don't (`USAGE`).
const VALUE_FLAGS: &[&str] = &[
    "--server",
    "--open",
    "--theme",
    "--width",
    "--height",
    "--scenario",
    "--shot",
    "--scale",
    "--shot-time",
    "--text",
    "--bench-frames",
];
const BARE_FLAGS: &[&str] = &["--mock", "--list-scenarios", "-h", "--help", "-V", "--version"];

/// Parses `--width` / `--height` (logical pixels): finite and at least 1 px. Interactive launches
/// cap logical dimensions at 16384 px; headless launches (`--shot` / `--bench-frames`) defer the
/// upper bound to `folo_ui`'s scale-aware device-pixel check so downscaled captures (e.g.
/// `--width 20000 --scale 0.5`) remain valid.
fn parse_window_dim(flag: &str, raw: &str, enforce_max: bool) -> Result<f32, String> {
    const MAX_DIM: f32 = 16384.0;
    let parsed =
        raw.parse::<f32>().ok().filter(|v| v.is_finite() && *v >= 1.0 && (!enforce_max || *v <= MAX_DIM));
    parsed.ok_or_else(|| {
        if enforce_max {
            format!("{flag} {raw}: expected a finite number from 1 to {MAX_DIM} (see --help)")
        } else {
            format!("{flag} {raw}: expected a finite number of at least 1 (see --help)")
        }
    })
}

/// What is wrong with `args` (without the program name) that the app would otherwise pass over in
/// silence: an unknown option, an option missing its value, an invalid `--width`/`--height`, a
/// theme that is no mode and no theme of `themes`, a scenario with an unknown screen or modifier,
/// or an invalid `--open` target. One stderr line each; interactive launches still open, while
/// headless launches (`--shot` / `--bench-frames`) fail closed on invalid arguments.
fn arg_warnings<S: AsRef<str>>(args: &[S], themes: &Catalog) -> Vec<String> {
    let is_headless = args.iter().any(|a| matches!(a.as_ref(), "--shot" | "--bench-frames"));
    let mut out = Vec::new();
    let mut i = 0;
    while i < args.len() {
        let a = args[i].as_ref();
        if VALUE_FLAGS.contains(&a) {
            match args.get(i + 1).map(AsRef::as_ref) {
                Some(v) if !v.starts_with("--") => {
                    if a == "--theme" && !ThemePrefs::default().apply_arg(v, themes) {
                        out.push(format!(
                            "--theme {v}: not dark, light, system or a theme's id; using the last theme, else dark"
                        ));
                    }
                    if a == "--scenario"
                        && let Err(err) = scenario::validate(v)
                    {
                        out.push(err);
                    }
                    if a == "--open" && v != "new-run" && app::Route::parse(v).is_none() {
                        out.push(format!("--open {v}: not a screen (see --help)"));
                    }
                    if (a == "--width" || a == "--height")
                        && let Err(err) = parse_window_dim(a, v, !is_headless)
                    {
                        out.push(err);
                    }
                    i += 2;
                    continue;
                }
                _ => out.push(format!("{a}: missing its value (see --help)")),
            }
        } else if a.starts_with('-') && !BARE_FLAGS.contains(&a) {
            out.push(format!("{a}: unknown option, ignored (see --help)"));
        }
        i += 1;
    }
    out
}

/// Errors that must fail a headless capture or benchmark (`--shot` or `--bench-frames`) before a
/// frame is rendered, so an invalid `--scenario`, `--open`, `--width`/`--height`, or conflicting
/// headless mode never silently produces a default PNG or suppresses a conflict diagnostic.
fn headless_arg_errors<S: AsRef<str>>(args: &[S]) -> Vec<String> {
    let has_shot = args.iter().any(|a| a.as_ref() == "--shot");
    let has_bench = args.iter().any(|a| a.as_ref() == "--bench-frames");
    if !has_shot && !has_bench {
        return Vec::new();
    }
    let mut out = Vec::new();
    if has_shot && has_bench {
        out.push("--shot and --bench-frames cannot be used together".to_string());
    }
    let mut i = 0;
    while i < args.len() {
        let a = args[i].as_ref();
        if VALUE_FLAGS.contains(&a) {
            match args.get(i + 1).map(AsRef::as_ref) {
                Some(v) if !v.starts_with("--") => {
                    if a == "--scenario"
                        && let Err(err) = scenario::validate(v)
                    {
                        out.push(err);
                    }
                    if a == "--open" && v != "new-run" && app::Route::parse(v).is_none() {
                        out.push(format!("--open {v}: not a screen (see --help)"));
                    }
                    if (a == "--width" || a == "--height")
                        && let Err(err) = parse_window_dim(a, v, false)
                    {
                        out.push(err);
                    }
                    i += 2;
                    continue;
                }
                _ => out.push(format!("{a}: missing its value (see --help)")),
            }
        }
        i += 1;
    }
    out
}

/// The theme choice to open with: the last launch's (else Dark with the default themes), changed by
/// `--theme` when that is a mode or a theme of `themes` (a bad `--theme x` used to win over the
/// remembered light theme, open dark and remember dark).
fn launch_prefs(cli: Option<&str>, saved: &window_state::State, themes: &Catalog) -> ThemePrefs {
    let mut prefs = saved.theme_prefs();
    if let Some(arg) = cli {
        prefs.apply_arg(arg, themes);
    }
    prefs
}

fn arg_value<'a, S: AsRef<str>>(args: &'a [S], name: &str) -> Option<&'a str> {
    args.iter()
        .position(|a| a.as_ref() == name)
        .and_then(|i| args.get(i + 1).map(AsRef::as_ref))
        .filter(|v| !v.starts_with("--"))
}

/// Run FOLO Desktop with the process's arguments: print `--help`, `--version` or `--list-scenarios`, else open
/// the window and run until it closes. The `folo-desktop` binary (`main.rs`) is just this call.
pub fn run() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if let Some(text) = info_text(&args) {
        print!("{text}");
        return;
    }
    if std::env::args().any(|a| a == "--list-scenarios") {
        for s in scenario::ALL {
            println!("{s}");
        }
        return;
    }
    // Custom themes are read before the arguments: `--theme` may name one.
    let themes = Catalog::load(&theme::catalog::custom_folder());
    let warnings = arg_warnings(&args, &themes);
    for warning in &warnings {
        eprintln!("folo-desktop: {warning}");
    }
    let headless_errors = headless_arg_errors(&args);
    if !headless_errors.is_empty() {
        for err in &headless_errors {
            if !warnings.contains(err) {
                eprintln!("folo-desktop: {err}");
            }
        }
        std::process::exit(2);
    }
    let scenario = arg_value(&args, "--scenario").map(str::to_string);
    let is_headless = args.iter().any(|a| matches!(a.as_str(), "--shot" | "--bench-frames"));
    let width_arg =
        arg_value(&args, "--width").and_then(|w| parse_window_dim("--width", w, !is_headless).ok());
    let height_arg =
        arg_value(&args, "--height").and_then(|h| parse_window_dim("--height", h, !is_headless).ok());
    let width = width_arg.unwrap_or(1280.0);
    let height = height_arg.unwrap_or(800.0);
    // The window and theme from the last launch, unless this one is for a screenshot or gave a
    // valid explicit size override (a malformed `--width` falls back to saved state).
    let remember = window_state::remembers(scenario.is_some(), width_arg.is_some() || height_arg.is_some());
    let state_path = remember.then(window_state::path);
    let saved = state_path.as_deref().map(window_state::load).unwrap_or_default();
    let mut prefs = launch_prefs(arg_value(&args, "--theme"), &saved, &themes);
    let spec = scenario.as_deref().map(scenario::Spec::parse);
    // Data source: `--server URL` connects to a running folo serve; `--mock` uses the built-in demo
    // data; by default the app finds or starts a server (see `FoloApp::autoconnect`).
    let server = arg_value(&args, "--server").map(str::to_string);
    // `--open run:run_3c02` starts on a screen (also `dataset:ID`, `model:ID`, `runs`, …).
    let open = arg_value(&args, "--open").map(str::to_string);
    let use_mock = args.iter().any(|a| a == "--mock");
    let default_url =
        launch_server_url(std::env::var("FOLO_SERVER").ok().as_deref(), saved.server_url.as_deref());

    Application::new().with_assets(Assets).run(move |cx: &mut App| {
        cx.text_system()
            .add_fonts(FONTS.iter().map(|f| Cow::Borrowed(*f)).collect())
            .expect("bundled fonts load");
        if let Some(mode) = spec.as_ref().and_then(|s| s.mode) {
            prefs.mode = mode.into();
        }
        let system_dark = app::is_dark(cx.window_appearance());
        cx.set_global(themes.resolve(&prefs, system_dark));
        app::bind_keys(cx);
        input::bind_keys(cx);

        let frozen = spec.is_some();
        let use_demo = spec.is_some() || use_mock;
        let auto = !use_demo && server.is_none();
        let connect_url = server.clone().unwrap_or(default_url.clone());
        let api: Arc<dyn api::Backend> = if use_demo {
            let live_step = spec.as_ref().map_or(4180, |s| s.live_step);
            let mut mock = if spec.as_ref().is_some_and(|s| s.cloud_runs) {
                MockBackend::with_cloud_runs(live_step, frozen)
            } else {
                MockBackend::new(live_step, frozen)
            };
            if spec.as_ref().is_some_and(|s| s.fail) {
                mock = mock.failing();
            }
            if spec.as_ref().is_some_and(|s| s.empty) {
                mock = mock.empty().without_cloud();
            }
            if spec.as_ref().is_some_and(|s| s.has("trouble")) {
                mock = mock.cloud_trouble();
            }
            if spec.as_ref().is_some_and(|s| s.has("silent")) {
                mock = mock.cloud_silent();
            }
            Arc::new(mock)
        } else {
            Arc::new(api::http::HttpBackend::new(&connect_url))
        };
        let server_mode = if use_demo { app::ServerMode::Mock } else { app::ServerMode::Local };
        let spawn_server = saved.spawn_server.unwrap_or(true);

        let (window_bounds, display_id) = match saved.window {
            Some(p) => restored_bounds(p, cx),
            None => (WindowBounds::Windowed(Bounds::centered(None, size(px(width), px(height)), cx)), None),
        };
        let window = cx
            .open_window(
                WindowOptions {
                    window_bounds: Some(window_bounds),
                    display_id,
                    titlebar: Some(TitlebarOptions {
                        title: Some("FOLO Desktop".into()),
                        appears_transparent: true,
                        traffic_light_position: Some(point(px(12.), px(12.))),
                    }),
                    window_min_size: Some(size(px(960.), px(620.))),
                    app_id: Some("folo-desktop".into()),
                    ..Default::default()
                },
                |window, cx| {
                    cx.new(|cx| {
                        let mut app = app::FoloApp::new(api, frozen, window, cx);
                        app.state_path = state_path.clone();
                        app.server_mode = server_mode;
                        app.themes = themes.clone();
                        app.theme_prefs = prefs.clone();
                        app.apply_theme(cx);
                        app.spawn_server = spawn_server;
                        app.saved_server_url = saved.server_url.clone();
                        app.sidebar_collapsed = saved.sidebar_collapsed.unwrap_or(false);
                        if let Some(calm) = saved.reduce_motion {
                            app.reduce_motion = calm;
                            crate::ui::set_reduce_motion(calm);
                        }
                        app.server_url.update(cx, |i, cx| i.set_text(connect_url.clone(), cx));
                        if let Some(s) = &spec {
                            scenario::apply(&mut app, s, window, cx);
                        }
                        if auto {
                            let spawn = should_auto_spawn(spawn_server, &connect_url);
                            app.autoconnect(connect_url.clone(), spawn, app::Reason::Launch, cx);
                        } else if server_mode == app::ServerMode::Local {
                            app.connected_url = Some(connect_url.clone());
                        }
                        if open.as_deref() == Some("new-run") {
                            app.open_new_run_pending = true;
                        } else if let Some(route) = open.as_deref().and_then(app::Route::parse) {
                            app.route = route;
                        }
                        let this = cx.weak_entity();
                        app::follow_system_appearance(window, this.clone(), cx);
                        window.on_window_should_close(cx, move |window, cx| {
                            this.update(cx, |app, cx| app.should_close(window, cx)).unwrap_or(true)
                        });
                        app
                    })
                },
            )
            .expect("open window");
        let _ = window;
        cx.on_window_closed(|cx| cx.quit()).detach();
        cx.activate(true);
    });
}

/// Where a remembered window opens: its saved bounds on the display it was on (matched by UUID) or
/// another that still shows its title bar, else centred on the primary display
/// (`window_state::place`), maximized or full screen as it was.
fn restored_bounds(p: window_state::Placement, cx: &App) -> (WindowBounds, Option<folo_ui::DisplayId>) {
    use window_state::{Rect, WindowMode};
    let rect = |b: Bounds<folo_ui::Pixels>| Rect {
        x: b.origin.x.into(),
        y: b.origin.y.into(),
        width: b.size.width.into(),
        height: b.size.height.into(),
    };
    let displays = cx.displays();
    let primary = cx.primary_display().map(|p| p.id());
    let primary = displays.iter().position(|d| Some(d.id()) == primary).unwrap_or(0);
    let rects: Vec<Rect> = displays.iter().map(|d| rect(d.bounds())).collect();
    let remembered = p
        .display
        .as_deref()
        .and_then(|uuid| displays.iter().position(|d| d.uuid().is_ok_and(|u| u.to_string() == uuid)));
    let saved = Rect { x: p.x, y: p.y, width: p.width, height: p.height };
    let (i, r) = window_state::place(saved, &rects, primary, remembered, theme::size::TOPBAR);
    let bounds = Bounds::new(point(px(r.x), px(r.y)), size(px(r.width), px(r.height)));
    let window_bounds = match p.mode {
        WindowMode::Windowed => WindowBounds::Windowed(bounds),
        WindowMode::Maximized => WindowBounds::Maximized(bounds),
        WindowMode::Fullscreen => WindowBounds::Fullscreen(bounds),
    };
    (window_bounds, displays.get(i).map(|d| d.id()))
}

/// Server URL used on launch when `--server` is not passed: `$FOLO_SERVER` wins over the URL
/// remembered in `desktop.json`, which wins over the default local address.
fn launch_server_url(env_server: Option<&str>, saved: Option<&str>) -> String {
    env_server
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .or_else(|| saved.map(str::trim).filter(|s| !s.is_empty()))
        .unwrap_or("http://127.0.0.1:7878")
        .to_string()
}

/// Whether launch-time autoconnect may spawn a local `folo serve`: only when auto-spawn is enabled
/// and the target URL is a valid loopback address, so a saved remote server is never silently
/// replaced by a local instance.
fn should_auto_spawn(spawn_server: bool, url: &str) -> bool {
    spawn_server && api::http::address_ok(url) && api::http::is_loopback(url)
}

#[cfg(test)]
mod source_tests {
    /// Catches text double-encoded by an editor or shell (UTF-8 read as Windows-1252) and stray BOMs.
    #[test]
    fn sources_are_clean_utf8() {
        fn walk(dir: &std::path::Path, bad: &mut Vec<String>) {
            for e in std::fs::read_dir(dir).unwrap().flatten() {
                let p = e.path();
                if p.is_dir() {
                    walk(&p, bad);
                } else if p.extension().is_some_and(|x| x == "rs") {
                    let s = std::fs::read_to_string(&p).unwrap();
                    if s.contains(['\u{00C3}', '\u{00C2}', '\u{00E2}', '\u{FEFF}']) {
                        bad.push(p.display().to_string());
                    }
                }
            }
        }
        let mut bad = Vec::new();
        walk(&std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src"), &mut bad);
        assert!(bad.is_empty(), "mojibake or BOM in {bad:?}");
    }
}

