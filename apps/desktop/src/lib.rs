//! FOLO Desktop: the native front end for FOLO, on folo-ui (`ui/`).
//!
//! `folo-desktop [--server URL | --mock] [--open SCREEN] [--scenario NAME] [--width W --height H]
//! [--theme MODE|THEME]`; `--help` and `--version` print and exit (see [`USAGE`]).
//!
//! Scenarios put the app into a fixed, deterministic state (frozen mock clock, a screen, an
//! overlay, a hover) for screenshots; see `scenario.rs` and `tools/shoot-all.ps1`.
//!
//! The app is this library and a thin `folo-desktop` binary (`main.rs`, which calls [`run`]), so cargo can start
//! compiling it as soon as its dependencies' metadata is ready instead of after their code generation
//! (README.md, Workspace, build, test).
//!
//! Modules (`README.md`, Where things are, has the full table):
//!
//! - `api`: the `Backend` trait, its HTTP client (`api::http`, which also starts a local `folo serve`) and
//!   the built-in demo (`api::mock`, `api::mock_bench`);
//! - `app`: `FoloApp`, the root view: routing (`Route`), chrome, sidebar, fetching, actions, key bindings;
//! - `screens`: one module per page; `overlays`: palette, dialogs, inspector, toasts;
//! - `controls`: focusable controls; `ui`: stateless pieces (this crate's, not the folo-ui crate);
//! - `charts`, `viz`: canvas charts, and images with detection boxes;
//! - `store`: fetched state, live run data, decoded images; `bench`, `cloud`: the state behind the
//!   Benchmarks screens and the cloud surfaces;
//! - `local`: Playground's in-process inference; `input`: the text input; `theme`: tokens from
//!   `design/tokens.json` (generated by `build.rs`); `window_state`: `desktop.json`;
//! - `scenario`, `synth`: `--scenario` states and the demo's procedural images.

