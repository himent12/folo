/// How often a dataset's files are re-checked for changes (on `GET /api/datasets/{id}` and image listings).
pub const RECHECK_EVERY: Duration = Duration::from_secs(5);
/// Most images `POST /api/datasets/synthetic` generates.
pub const MAX_SYNTHETIC_IMAGES: u64 = 100_000;
/// How long [`Store::shutdown`](crate::store::Store::shutdown) waits for the active run to stop at a batch
/// boundary.
pub const SHUTDOWN_WAIT: Duration = Duration::from_secs(60);
/// The GPU buffer pool's cached buffers go back to the driver after this long without a prediction, validation,
/// evaluation or benchmark probe, while no run is queued or training ([`RealStore::gpu_idle_release`]; a finished
/// run releases its own at once).
pub const GPU_IDLE_RELEASE: Duration = Duration::from_secs(30);
/// Cached predictors (loaded models, [`crate::engine::PREDICTOR_CACHE`]) are dropped after this long without any
/// of those, so an idle server holds no model memory either.
pub const PREDICTOR_IDLE: Duration = Duration::from_secs(300);

#[derive(Clone, Debug, Serialize, Deserialize)]
struct Registration {
    id: String,
    name: String,
    path: String,
    format: DatasetFormat,
    created: String,
    /// Snapshot for listing before the index is loaded (absent in registries written by older versions).
    #[serde(default)]
    classes: Vec<String>,
    #[serde(default)]
    splits: Splits,
}

enum State {
    /// Being built or loaded; wait on [`Entry::ready`].
    Pending,
    Ready(Arc<Index>),
    Failed(Error),
}

struct Slot {
    state: State,
    /// When the fingerprint was last compared with the files.
    checked: Instant,
    /// A re-check is running (other requests keep using the current index meanwhile).
    checking: bool,
}

/// One registered dataset.
struct Entry {
    reg: Mutex<Registration>,
    slot: Mutex<Slot>,
    ready: Condvar,
    /// True once unregistered. Every cache write (index, thumbnails) holds this lock and skips the write when it is
    /// set, and unregistering sets it before deleting the caches, so an indexer or thumbnail still in flight never
    /// recreates the cache of a deleted dataset.
    deleted: Mutex<bool>,
}

impl Entry {
    fn new(reg: Registration, state: State) -> Entry {
        Entry {
            reg: Mutex::new(reg),
            slot: Mutex::new(Slot { state, checked: Instant::now(), checking: false }),
            ready: Condvar::new(),
            deleted: Mutex::new(false),
        }
    }

    /// Runs a cache write unless the dataset was unregistered (see [`Entry::deleted`]).
    fn write_cache(&self, write: impl FnOnce()) {
        let deleted = self.deleted.lock().unwrap();
        if !*deleted {
            write();
        }
    }

    fn reg(&self) -> Registration {
        self.reg.lock().unwrap().clone()
    }

    fn set(&self, state: State) {
        let mut slot = self.slot.lock().unwrap();
        slot.state = state;
        slot.checked = Instant::now();
        slot.checking = false;
        self.ready.notify_all();
    }

    /// The current index, waiting while it is being built.
    fn current(&self) -> Result<Arc<Index>> {
        let mut slot = self.slot.lock().unwrap();
        loop {
            match &slot.state {
                State::Pending => slot = self.ready.wait(slot).unwrap(),
                State::Ready(i) => return Ok(i.clone()),
                State::Failed(e) => return Err(e.clone()),
            }
        }
    }
}

/// The real store. See the module docs.
pub struct RealStore {
    data_dir: PathBuf,
    entries: RwLock<Vec<Arc<Entry>>>,
    /// Held shared while a dataset is registered and while a run is created or resumed, exclusively while
    /// `DELETE /api/datasets/{id}?files=true` checks that nothing reads the folder and deletes it.
    files: RwLock<()>,
    recheck_every: Duration,
    runs: Arc<Runs>,
    models: Models,
    predictors: Arc<Predictors>,
    idle: Arc<GpuIdle>,
    device: String,
    precision: folo_vision::Precision,
    throughput: Arc<Throughput>,
    uploads: Arc<Uploads>,
    cloud: Cloud,
    labeler: Labeler,
    benches: Benches,
}

impl RealStore {
    /// Opens the store rooted at `data_dir`. Registered datasets are listed right away and indexed on a background
    /// thread (from the cache when it is fresh). Datasets whose folder is gone are kept out of the list (and
    /// logged) but stay in the registry file. Cloud runs a previous process left are picked up
    /// ([`crate::cloud`]), with FOLO's providers ([`folo_cloud::providers`]).
    pub fn open(data_dir: PathBuf) -> RealStore {
        RealStore::open_with_cloud(data_dir, folo_cloud::providers(), cloud::Tuning::default())
    }

    /// [`RealStore::open`] with these cloud providers and timings. They are given at open because the cloud runs a
    /// previous process left are picked up (and the reaper starts) right away; tests pass an in-process provider
    /// and short timings.
    pub fn open_with_cloud(
        data_dir: PathBuf,
        providers: Vec<Arc<dyn folo_cloud::Provider>>,
        tuning: cloud::Tuning,
    ) -> RealStore {
        let regs = read_registry(&data_dir).map(|f| f.datasets).unwrap_or_else(|e| {
            tracing::error!("{e}; registering and unregistering datasets is disabled until it is fixed");
            Vec::new()
        });
        // A dataset whose folder is gone stays listed (indexing fails with `path_not_found`), so clients can say so
        // and unregister it; it works again as soon as the folder is back.
        let entries: Vec<_> = regs.into_iter().map(|r| Arc::new(Entry::new(r, State::Pending))).collect();
        if !entries.is_empty() {
            let todo = entries.clone();
            let dir = data_dir.clone();
            let spawned = std::thread::Builder::new().name("folo-index".into()).spawn(move || {
                for e in todo {
                    load_or_build(&dir, &e);
                }
            });
            if let Err(err) = spawned {
                tracing::error!("could not start the indexing thread: {err}");
                for e in &entries {
                    e.set(State::Failed(Error::internal("indexing thread did not start")));
                }
            }
        }
        let throughput = Arc::new(Throughput::open(data_dir.join(crate::throughput::FILE)));
        let runs = Runs::open(data_dir.join("runs"), throughput.clone());
        let models = Models::new(data_dir.clone());
        let predictors = Arc::new(Predictors::default());
        let idle = Arc::new(GpuIdle::new());
        let labeler = Labeler::open(&data_dir);
        // Benchmark entries count as inference for the idle sweeper, as predictions do.
        let guard: crate::bench::InferenceGuard = {
            let idle = idle.clone();
            Arc::new(move |device| {
                let g = idle.using();
                g.on(device);
                Box::new(g)
            })
        };
        let benches = Benches::open(&data_dir, Some(guard));
        spawn_idle_sweeper(Arc::downgrade(&idle), Arc::downgrade(&predictors), Arc::downgrade(&runs));
        let uploads = Uploads::open(&data_dir);
        let cloud = Cloud::with(&data_dir, providers, tuning);
        cloud.recover_and_reap(&runs);
        RealStore {
            data_dir,
            entries: RwLock::new(entries),
            files: RwLock::new(()),
            recheck_every: RECHECK_EVERY,
            runs,
            models,
            predictors,
            idle,
            device: "auto".into(),
            precision: folo_vision::Precision::F32,
            throughput,
            uploads,
            cloud,
            labeler,
            benches,
        }
    }

    /// The precision of `/api/predict` and `/api/val` (f32, the default; f16 runs in half precision on a GPU with
    /// `shader-f16` and falls back to f32, with a warning in the log, elsewhere). The cached `/eval` metrics stay
    /// f32.
    pub fn precision(mut self, precision: folo_vision::Precision) -> RealStore {
        self.precision = precision;
        self
    }

    /// The device of inference and `/eval` (`auto`, the default: the GPU when one can hold the model, else the
    /// CPU; `cpu`; `gpu:<n>`). Training uses each run's `TrainConfig.device`.
    pub fn device(mut self, device: impl Into<String>) -> RealStore {
        self.device = device.into();
        self.benches.set_device(&self.device);
        self
    }

    /// Lists the published weights downloaded into `dir` as models (`Model.source: published`, id = the published
    /// name), so `TrainConfig.weights: "folo-n-coco"` works as `folo train --weights folo-n-coco` does. `folo serve`
    /// and `folo mcp` pass [`folo_api::weights::cache_dir`]; by default none are listed.
    pub fn published_weights(mut self, dir: impl Into<PathBuf>) -> RealStore {
        self.models.set_published(Some(dir.into()));
        self
    }

    /// Changes how long inference may be idle before the GPU pool's cached buffers are released (default
    /// [`GPU_IDLE_RELEASE`]) and the cached predictors dropped (default [`PREDICTOR_IDLE`]).
    pub fn gpu_idle_release(self, pool: Duration, predictors: Duration) -> RealStore {
        self.idle.release_after_ms.store(pool.as_millis() as u64, Ordering::Relaxed);
        self.idle.predictors_after_ms.store(predictors.as_millis() as u64, Ordering::Relaxed);
        self
    }

    /// Changes how long an upload session may go without a part before it expires (default
    /// [`crate::uploads::UPLOAD_IDLE`]).
    pub fn upload_idle(self, idle: Duration) -> RealStore {
        self.uploads.set_idle(idle);
        self
    }

    /// Test support: while `on`, every training run waits after each epoch (checkpoint written, `epoch` event sent)
    /// until this is turned off or the run is asked to stop. Tests use it to stop a run deterministically before it
    /// could finish on its own; nothing else turns it on.
    #[doc(hidden)]
    pub fn hold_runs_after_epochs(&self, on: bool) {
        self.runs.hold_after_epochs(on);
    }

    /// How long an open external benchmark entry waits for its next part before it expires (default 30 minutes;
    /// tests shorten it).
    pub fn bench_open_timeout(self, timeout: Duration) -> RealStore {
        self.benches.set_open_timeout(timeout);
        self
    }

    /// Test support: while `on`, every benchmark model entry waits after its last pass, before it is graded (a
    /// stop can then land while it is graded). Nothing else turns it on.
    #[doc(hidden)]
    pub fn hold_bench_entries(&self, on: bool) {
        self.benches.hold_entries(on);
    }

    /// Test support: replaces the labeling agents (Claude Code and Codex) with scripted ones, so tests exercise
    /// agent labeling without a CLI or an account.
    #[doc(hidden)]
    pub fn label_agents(mut self, agents: Vec<Arc<dyn crate::label::Agent>>) -> RealStore {
        self.labeler.set_agents(agents);
        self
    }

    /// Test support: how often a labeling run writes its job's file at most (default 5 s), so a test of that save
    /// need not wait for it.
    #[doc(hidden)]
    pub fn label_save_every(mut self, every: Duration) -> RealStore {
        self.labeler.set_save_every(every);
        self
    }

    /// Changes how often dataset files are re-checked for changes (default [`RECHECK_EVERY`]; zero checks on
    /// every request).
    pub fn recheck_every(mut self, every: Duration) -> RealStore {
        self.recheck_every = every;
        self
    }
}

impl Drop for RealStore {
    fn drop(&mut self) {
        self.benches.shutdown();
        self.labeler.shutdown();
        self.runs.shutdown(None);
    }
}

