/// How often a dataset's files are re-checked for changes (on `GET /api/datasets/{id}` and image listings).
pub const RECHECK_EVERY: Duration = Duration::from_secs(5);
/// Most images `POST /api/datasets/synthetic` generates.
pub const MAX_SYNTHETIC_IMAGES: u64 = 100_000;

#[derive(Clone, Debug, Serialize, Deserialize)]
struct Registration {
    id: String,
    name: String,
    path: String,
    format: DatasetFormat,
    created: String,
    /// Snapshot for listing before the index is loaded (absent in registries written by older versions).
    #[serde(default)]
    classes: Vec<String>,
    #[serde(default)]
    splits: Splits,
}

enum State {
    /// Being built or loaded; wait on [`Entry::ready`].
    Pending,
    Ready(Arc<Index>),
    Failed(Error),
}

struct Slot {
    state: State,
    /// When the fingerprint was last compared with the files.
    checked: Instant,
    /// A re-check is running (other requests keep using the current index meanwhile).
    checking: bool,
}

/// One registered dataset.
struct Entry {
    reg: Mutex<Registration>,
    slot: Mutex<Slot>,
    ready: Condvar,
    /// True once unregistered. Every cache write (index, thumbnails) holds this lock and skips the write when it is
    /// set, and unregistering sets it before deleting the caches, so an indexer or thumbnail still in flight never
    /// recreates the cache of a deleted dataset.
    deleted: Mutex<bool>,
}

impl Entry {
    fn new(reg: Registration, state: State) -> Entry {
        Entry {
            reg: Mutex::new(reg),
            slot: Mutex::new(Slot { state, checked: Instant::now(), checking: false }),
            ready: Condvar::new(),
            deleted: Mutex::new(false),
        }
    }

    /// Runs a cache write unless the dataset was unregistered (see [`Entry::deleted`]).
    fn write_cache(&self, write: impl FnOnce()) {
        let deleted = self.deleted.lock().unwrap();
        if !*deleted {
            write();
        }
    }

    fn reg(&self) -> Registration {
        self.reg.lock().unwrap().clone()
    }

    fn set(&self, state: State) {
        let mut slot = self.slot.lock().unwrap();
        slot.state = state;
        slot.checked = Instant::now();
        slot.checking = false;
        self.ready.notify_all();
    }

    /// The current index, waiting while it is being built.
    fn current(&self) -> Result<Arc<Index>> {
        let mut slot = self.slot.lock().unwrap();
        loop {
            match &slot.state {
                State::Pending => slot = self.ready.wait(slot).unwrap(),
                State::Ready(i) => return Ok(i.clone()),
                State::Failed(e) => return Err(e.clone()),
            }
        }
    }
}

/// The real store. See the module docs.
pub struct RealStore {
    data_dir: PathBuf,
    entries: RwLock<Vec<Arc<Entry>>>,
    recheck_every: Duration,
}

impl RealStore {
    /// Opens the store rooted at `data_dir`. Registered datasets are listed right away and indexed on a background
    /// thread (from the cache when it is fresh). Datasets whose folder is gone are kept out of the list (and
    /// logged) but stay in the registry file.
    pub fn open(data_dir: PathBuf) -> RealStore {
        let regs = read_registry(&data_dir).unwrap_or_else(|e| {
            tracing::error!("{e}; registering and unregistering datasets is disabled until it is fixed");
            Vec::new()
        });
        let mut entries = Vec::new();
        for r in regs {
            if !Path::new(&r.path).exists() {
                tracing::warn!(id = %r.id, path = %r.path, "skipping registered dataset: the path does not exist");
                continue;
            }
            entries.push(Arc::new(Entry::new(r, State::Pending)));
        }
        if !entries.is_empty() {
            let todo = entries.clone();
            let dir = data_dir.clone();
            let spawned = std::thread::Builder::new().name("folo-index".into()).spawn(move || {
                for e in todo {
                    load_or_build(&dir, &e);
                }
            });
            if let Err(err) = spawned {
                tracing::error!("could not start the indexing thread: {err}");
                for e in &entries {
                    e.set(State::Failed(Error::internal("indexing thread did not start")));
                }
            }
        }
        RealStore { data_dir, entries: RwLock::new(entries), recheck_every: RECHECK_EVERY }
    }

    /// Changes how often dataset files are re-checked for changes (default [`RECHECK_EVERY`]; zero checks on
    /// every request).
    pub fn recheck_every(mut self, every: Duration) -> RealStore {
        self.recheck_every = every;
        self
    }

    fn entry(&self, id: &str) -> Result<Arc<Entry>> {
        self.entries
            .read()
            .unwrap()
            .iter()
            .find(|e| e.reg.lock().unwrap().id == id)
            .cloned()
            .ok_or_else(|| Error::not_found("dataset", id))
    }

    /// The dataset's index, rebuilt first when its files changed (checked at most every `recheck_every`; a dataset
    /// that failed to index is retried as often).
    fn fresh_index(&self, e: &Entry) -> Result<Arc<Index>> {
        let current = e.current();
        {
            let mut slot = e.slot.lock().unwrap();
            if slot.checking || slot.checked.elapsed() < self.recheck_every {
                return current;
            }
            slot.checking = true;
        }
        if let Ok(cur) = &current
            && Fingerprint::of(&cur.watched, &cur.excluded) == cur.fingerprint
        {
            let mut slot = e.slot.lock().unwrap();
            slot.checked = Instant::now();
            slot.checking = false;
            return current;
        }
        let reg = e.reg();
        tracing::info!(id = %reg.id, "dataset files changed; re-indexing");
        match Index::build(&reg.path, reg.format, &own_state(&self.data_dir)) {
            Ok(idx) => {
                let idx = Arc::new(idx);
                save_index(&self.data_dir, e, &idx);
                self.snapshot(e, &idx);
                e.set(State::Ready(idx.clone()));
                Ok(idx)
            }
            Err(err) => {
                e.set(State::Failed(err.clone()));
                Err(err)
            }
        }
    }

    /// Updates the registry's classes / splits snapshot when they changed.
    fn snapshot(&self, e: &Entry, idx: &Index) {
        let _list = self.entries.write().unwrap();
        let changed = {
            let mut r = e.reg.lock().unwrap();
            let changed = r.classes != idx.classes || r.splits != idx.splits;
            r.classes = idx.classes.clone();
            r.splits = idx.splits;
            changed
        };
        if changed && let Ok(mut regs) = read_registry(&self.data_dir) {
            let r = e.reg();
            for x in regs.iter_mut().filter(|x| x.id == r.id) {
                *x = r.clone();
            }
            if let Err(err) = write_registry(&self.data_dir, &regs) {
                tracing::warn!("{err}");
            }
        }
    }

    fn meta(reg: &Registration, idx: Option<&Index>) -> Dataset {
        Dataset {
            id: reg.id.clone(),
            name: reg.name.clone(),
            path: reg.path.clone(),
            format: idx.map_or(reg.format, |i| i.format),
            classes: idx.map_or_else(|| reg.classes.clone(), |i| i.classes.clone()),
            created: reg.created.clone(),
            splits: idx.map_or(reg.splits, |i| i.splits),
            stats: idx.map(|i| i.stats.clone()),
        }
    }

    /// Indexes `path` and adds it to the registry.
    fn register(&self, name: Option<String>, path: String, format: DatasetFormat) -> Result<Dataset> {
        // Registered absolute, so the registry works whatever the working directory of the next start.
        let path = absolute(Path::new(&path)).to_string_lossy().into_owned();
        let idx = Arc::new(Index::build(&path, format, &own_state(&self.data_dir))?);
        let mut list = self.entries.write().unwrap();
        let mut regs = read_registry(&self.data_dir)?;
        // Unique against loaded datasets and registrations whose folder is currently missing.
        let id = unique_id("ds", fnv1a(path.as_bytes()) ^ unix_now().to_bits(), |id| {
            list.iter().any(|e| e.reg.lock().unwrap().id == id) || regs.iter().any(|r| r.id == id)
        });
        let name = name.filter(|n| !n.trim().is_empty()).unwrap_or_else(|| {
            idx.base.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_else(|| "dataset".into())
        });
        let reg = Registration {
            id,
            name,
            path,
            format: idx.format,
            created: rfc3339(unix_now()),
            classes: idx.classes.clone(),
            splits: idx.splits,
        };
        regs.push(reg.clone());
        write_registry(&self.data_dir, &regs)?;
        let out = Self::meta(&reg, Some(&idx));
        let entry = Arc::new(Entry::new(reg, State::Ready(idx.clone())));
        save_index(&self.data_dir, &entry, &idx);
        list.push(entry);
        Ok(out)
    }

    fn thumbs_dir(&self, id: &str) -> PathBuf {
        self.data_dir.join("cache").join("thumbs").join(id)
    }
}

/// The server's own files in the data dir, left out of dataset fingerprints (the data dir may sit inside a
/// registered dataset folder; caching an index must not make it stale).
fn own_state(dir: &Path) -> Vec<PathBuf> {
    vec![dir.join("cache"), registry_path(dir)]
}

fn registry_path(dir: &Path) -> PathBuf {
    dir.join("datasets.json")
}

fn index_path(dir: &Path, id: &str) -> PathBuf {
    dir.join("cache").join("datasets").join(format!("{id}.json"))
}

/// The registry. A missing file is an empty registry; an unreadable or malformed one is an error, so it is never
/// overwritten (and its registrations lost) by the next write.
fn read_registry(dir: &Path) -> Result<Vec<Registration>> {
    let path = registry_path(dir);
    let text = match std::fs::read_to_string(&path) {
        Ok(t) => t,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(e) => return Err(Error::internal(format!("reading {}: {e}", path.display()))),
    };
    serde_json::from_str(&text).map_err(|e| {
        Error::internal(format!("{} is malformed: {e}", path.display()))
            .hint("fix the JSON by hand or move the file away; FOLO will not overwrite it")
    })
}

fn write_registry(dir: &Path, regs: &[Registration]) -> Result<()> {
    let path = registry_path(dir);
    let bytes = serde_json::to_vec_pretty(regs).expect("registrations serialize");
    write_atomic(&path, &bytes).map_err(|e| Error::internal(format!("writing {}: {e}", path.display())))
}

fn save_index(dir: &Path, e: &Entry, idx: &Index) {
    let id = e.reg().id;
    let path = index_path(dir, &id);
    let bytes = serde_json::to_vec(idx).expect("indexes serialize");
    e.write_cache(|| {
        if let Err(err) = write_atomic(&path, &bytes) {
            tracing::warn!("caching the index of {id} in {}: {err}", path.display());
        }
    });
}

/// Startup: loads the cached index when it is fresh, rebuilds it otherwise.
fn load_or_build(dir: &Path, e: &Entry) {
    let reg = e.reg();
    let cached = std::fs::read(index_path(dir, &reg.id))
        .ok()
        .and_then(|b| serde_json::from_slice::<Index>(&b).ok())
        .filter(|i| i.version == INDEX_VERSION)
        // A cache built without the read guard may hold data from files the guard refuses: rebuild under it.
        .filter(|_| !folo_data::guard::installed());
    if let Some(idx) = cached
        && idx.is_fresh()
    {
        tracing::debug!(id = %reg.id, "loaded the cached index");
        e.set(State::Ready(Arc::new(idx)));
        return;
    }
    let t0 = Instant::now();
    match Index::build(&reg.path, reg.format, &own_state(dir)) {
        Ok(idx) => {
            tracing::info!(id = %reg.id, images = idx.images.len(), secs = t0.elapsed().as_secs_f32(), "indexed");
            save_index(dir, e, &idx);
            e.set(State::Ready(Arc::new(idx)));
        }
        Err(err) => {
            tracing::warn!(id = %reg.id, path = %reg.path, "indexing failed: {err}");
            e.set(State::Failed(err));
        }
    }
}

/// A folder name for a dataset name: lowercase ASCII letters, digits and `-`.
fn slug(name: &str) -> String {
    let mut s = String::new();
    for c in name.trim().chars() {
        if c.is_ascii_alphanumeric() {
            s.push(c.to_ascii_lowercase());
        } else if !s.ends_with('-') && !s.is_empty() {
            s.push('-');
        }
    }
    let s = s.trim_end_matches('-').chars().take(48).collect::<String>();
    if s.is_empty() { "synthetic".into() } else { s }
}

impl Store for RealStore {
    fn is_mock(&self) -> bool {
        false
    }

    fn gpus(&self) -> Vec<GpuInfo> {
        // TODO(gpu): enumerate adapters through folo-gpu once it exists.
        Vec::new()
    }

    fn list_datasets(&self) -> Result<Vec<Dataset>> {
        let list = self.entries.read().unwrap().clone();
        Ok(list
            .iter()
            .map(|e| {
                let idx = match &e.slot.lock().unwrap().state {
                    State::Ready(i) => Some(i.clone()),
                    _ => None,
                };
                Dataset { stats: None, ..Self::meta(&e.reg(), idx.as_deref()) }
            })
            .collect())
    }

    fn register_dataset(&self, req: RegisterDataset) -> Result<Dataset> {
        self.register(req.name, req.path, req.format)
    }

    fn create_synthetic(&self, req: SyntheticDataset) -> Result<Dataset> {
        let bad = |m: String| Error::new(StatusCode::BAD_REQUEST, "invalid_body", m);
        if req.name.trim().is_empty() {
            return Err(bad("name must not be empty".into()));
        }
        if !(1..=MAX_SYNTHETIC_IMAGES).contains(&req.images) {
            return Err(bad(format!("images must be in 1..={MAX_SYNTHETIC_IMAGES}")));
        }
        if !(32..=4096).contains(&req.imgsz) {
            return Err(bad("imgsz must be in 32..=4096".into()));
        }
        let names: Vec<String> = req.classes.iter().map(|c| c.trim().to_string()).collect();
        let shapes = folo_data::synthetic::shapes_for(&names).map_err(|e| bad(e.to_string()))?;
        let cfg = folo_data::synthetic::SyntheticConfig {
            images: req.images as usize,
            classes: shapes,
            names,
            imgsz: req.imgsz,
            seed: req.seed,
            vary_aspect: false,
            val_fraction: 0.2,
            ..Default::default()
        };
        let parent = self.data_dir.join("datasets");
        let base = slug(&req.name);
        std::fs::create_dir_all(&parent)
            .map_err(|e| Error::internal(format!("creating {}: {e}", parent.display())))?;
        // create_dir claims the folder atomically, so concurrent requests with the same name never share one.
        let mut dir = parent.join(&base);
        let mut n = 1;
        loop {
            match std::fs::create_dir(&dir) {
                Ok(()) => break,
                Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => {
                    n += 1;
                    dir = parent.join(format!("{base}-{n}"));
                }
                Err(e) => return Err(Error::internal(format!("creating {}: {e}", dir.display()))),
            }
        }
        let t0 = Instant::now();
        if let Err(e) = folo_data::synthetic::write_yolo(&cfg, &dir, folo_data::ImageFormat::Jpeg(90)) {
            let _ = std::fs::remove_dir_all(&dir);
            return Err(data_error(e, &dir.to_string_lossy()));
        }
        tracing::info!(path = %dir.display(), images = cfg.images, secs = t0.elapsed().as_secs_f32(), "generated");
        let path = dir.to_string_lossy().into_owned();
        self.register(Some(req.name.trim().to_string()), path, DatasetFormat::Yolo)
    }

    fn get_dataset(&self, id: &str) -> Result<Dataset> {
        let e = self.entry(id)?;
        let idx = self.fresh_index(&e)?;
        Ok(Self::meta(&e.reg(), Some(&idx)))
    }

    fn list_images(&self, id: &str, q: &ImageQuery) -> Result<ImagePage> {
        let e = self.entry(id)?;
        Ok(self.fresh_index(&e)?.list_images(q))
    }

    fn list_issues(&self, id: &str, q: &IssueQuery) -> Result<folo_api::IssuePage> {
        let e = self.entry(id)?;
        Ok(self.fresh_index(&e)?.list_issues(q))
    }

    fn image(&self, id: &str, image_id: &str, thumb: Option<u32>) -> Result<ImageData> {
        let e = self.entry(id)?;
        let path = e.current()?.image_path(image_id)?;
        let cache = thumb.map(|_| self.thumbs_dir(id));
        read_image_with(&path, thumb, cache.as_deref(), |file, bytes| {
            e.write_cache(|| {
                if let Err(err) = write_atomic(file, bytes) {
                    tracing::warn!("caching thumbnail {}: {err}", file.display());
                }
            })
        })
    }

    fn delete_dataset(&self, id: &str) -> Result<()> {
        let mut list = self.entries.write().unwrap();
        let mut regs = read_registry(&self.data_dir)?;
        let found = list.iter().any(|e| e.reg.lock().unwrap().id == id) || regs.iter().any(|r| r.id == id);
        if !found {
            return Err(Error::not_found("dataset", id));
        }
        regs.retain(|r| r.id != id);
        write_registry(&self.data_dir, &regs)?;
        let entry = list.iter().find(|e| e.reg.lock().unwrap().id == id).cloned();
        list.retain(|e| e.reg.lock().unwrap().id != id);
        // Caches are ours to delete; the dataset's own files never are. Marking the entry deleted first (under the
        // lock cache writers hold) keeps in-flight indexers and thumbnails from writing them back.
        let _deleted = entry.as_ref().map(|e| {
            let mut d = e.deleted.lock().unwrap();
            *d = true;
            d
        });
        let _ = std::fs::remove_file(index_path(&self.data_dir, id));
        let _ = std::fs::remove_dir_all(self.thumbs_dir(id));
        Ok(())
    }

    fn list_models(&self) -> Result<Vec<Model>> {
        // TODO(engine): list `.folo` files under `<data_dir>/models` and run outputs once the format reader exists.
        Ok(Vec::new())
    }

    fn get_model(&self, id: &str) -> Result<Model> {
        Err(Error::not_found("model", id))
    }

    fn model_eval(&self, id: &str) -> Result<ModelEval> {
        Err(Error::not_found("model", id))
    }

    fn export_model(&self, id: &str, _format: ExportFormat) -> Result<ExportResult> {
        Err(Error::not_found("model", id))
    }

    fn list_runs(&self) -> Result<Vec<Run>> {
        Ok(Vec::new())
    }

    fn create_run(&self, config: TrainConfig) -> Result<Run> {
        self.entry(&config.dataset_id)?;
        Err(Error::not_implemented("training"))
    }

    fn get_run(&self, id: &str) -> Result<Run> {
        Err(Error::not_found("run", id))
    }

    fn stop_run(&self, id: &str) -> Result<Run> {
        Err(Error::not_found("run", id))
    }

    fn delete_run(&self, id: &str) -> Result<()> {
        Err(Error::not_found("run", id))
    }

    fn run_metrics(&self, id: &str, _every: u64) -> Result<RunMetrics> {
        Err(Error::not_found("run", id))
    }

    fn run_samples(&self, id: &str, _epoch: Option<u32>) -> Result<RunSamples> {
        Err(Error::not_found("run", id))
    }

    fn run_logs(&self, id: &str, _limit: usize) -> Result<Vec<LogLine>> {
        Err(Error::not_found("run", id))
    }

    fn subscribe(&self, id: &str) -> Result<Subscription> {
        Err(Error::not_found("run", id))
    }

    fn predict(&self, input: PredictInput) -> Result<PredictResponse> {
        if let PredictSource::Dataset { dataset_id, .. } = &input.source {
            self.entry(dataset_id)?;
        }
        Err(Error::not_implemented("inference"))
    }
}

