//! `RealStore`: datasets on disk read with folo-data, training runs on folo-vision's trainer ([`crate::runs`]),
//! models from runs and the models folder ([`crate::models`]) and inference through a predictor cache
//! ([`crate::engine`]).
//!
//! Layout of the data dir:
//! - `datasets.json`: the registry (id, name, path, format, created, plus a snapshot of classes and splits), written
//!   atomically (temporary file + rename) on every change.
//! - `cache/datasets/<id>.json`: the dataset's [`Index`] (images, boxes, stats) and the [`Fingerprint`] of the files
//!   it was built from. On start every registered dataset is checked on a background thread: a fresh cache is
//!   loaded, a stale or missing one is rebuilt. Requests for a dataset that is still being indexed wait for it.
//!   `GET /api/datasets/{id}` and image listings re-check the fingerprint at most every [`RECHECK_EVERY`].
//! - `cache/thumbs/<id>/`: JPEG thumbnails, keyed by the image's path, size, mtime and the thumbnail side.
//! - `datasets/<name>/`: synthetic datasets generated by `POST /api/datasets/synthetic`.
//! - `runs/<id>/`: training runs (see [`crate::runs`]).
//! - `models/`: `.folo` files listed as models (scanned on every listing).
//! - `exports/`: `POST /api/models/{id}/export` output.
//! - `cache/eval/<model id>.json`: cached `/eval` results (`POST /api/val` is computed on every request).
//! - `cache/weights/<model id>.<hash>.f16.folo`: f16 exports served by `GET /api/models/{id}/weights?format=f16`.

